#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


ACTIVE_PAGES = ("CI", "RP", "SD", "LR", "SI", "DM", "NR", "AE", "LB", "DG", "DH")
REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUTPUT = (
    REPO_ROOT
    / "crates/services/web-server/tests/api_editor/pages"
)


def load_contract(registry_root: Path, page_id: str) -> dict:
    path = registry_root / "editor-contracts" / f"{page_id.lower()}.json"
    contract = json.loads(path.read_text(encoding="utf-8"))
    if contract.get("pageId") != page_id:
        raise ValueError(f"{path}: expected pageId {page_id}")
    return contract


def test_name(code: str) -> str:
    normalized = re.sub(r"[^a-z0-9]+", "_", code.lower()).strip("_")
    if not normalized:
        raise ValueError(f"cannot generate test name for {code!r}")
    if normalized[0].isdigit():
        normalized = f"field_{normalized}"
    return normalized


def render_page(page_id: str, fields: list[dict], checks: dict | None = None) -> str:
    declarations = []
    blocked = []
    names = set()
    for field in sorted(fields, key=lambda item: item["code"]):
        execution = field.get("execution", {})
        if execution.get("status") == "blocked":
            reason = execution.get("reason")
            if not isinstance(reason, str) or not reason.strip():
                raise ValueError(
                    f'{page_id} {field["code"]}: blocked execution requires a reason'
                )
            normalized_reason = " ".join(reason.split())
            blocked.append(
                f'// BLOCKED editor contract {field["code"]}: {normalized_reason}'
            )
            continue
        name = test_name(field["code"])
        if name in names:
            raise ValueError(f"duplicate generated test name {name} in {page_id}")
        names.add(name)
        declarations.append(
            f'field_contract_test!({name}, "{field["code"]}");'
        )
    body = "mod fields {\n    use crate::case_editor_contract_web::fields::field_contract_test;\n" + f'    const PAGE_ID: &str = "{page_id}";\n' + "\n".join("    " + line for line in [*blocked, *declarations]) + "\n"
    checks = checks if checks is not None else {}
    for group, category in (("fieldChecks", "fields"), ("collections", "rows"), ("relations", "relations"), ("auditChecks", "audit")):
        if category != "fields":
            body += f"mod {category} {{\n"
        seen = set(names) if category == "fields" else set()
        for check in checks.get(group, []):
            name, verifier = check["id"], check["verifier"]
            if not re.fullmatch(r"[a-z][a-z0-9_]+", name) or name in seen:
                raise ValueError(f"{page_id}: invalid or duplicate {category} check {name}")
            if not re.fullmatch(r"(?:fields|rows|relations|audit)::[a-z][a-z0-9_]*::[a-z][a-z0-9_]*", verifier) or not verifier.startswith(category + "::"):
                raise ValueError(f"{page_id}/{name}: invalid {category} verifier {verifier}")
            seen.add(name)
            body += ("    #[serial_test::serial]\n    #[tokio::test]\n"
                     f"    async fn {name}() -> crate::common::Result<()> {{\n"
                     f'        crate::case_editor_contract_web::{verifier}("{page_id}", "{name}").await\n'
                     "    }\n")
        body += "}\n"

    return (
        "// @generated by registry/tools/generate_editor_contract_web_tests.py.\n"
        "// Do not edit by hand.\n\n"
        f"{body}"
    )


def validate_behavior_bindings(contract: dict, registry_root: Path) -> None:
    page = contract["pageId"]
    identities = contract.get("rowIdentities")
    if not isinstance(identities, dict):
        raise ValueError(f"{page}: missing row identity contracts")
    used = set()
    for field in contract["fields"]:
        if field.get("execution", {}).get("status") == "blocked":
            continue
        request = field["patch"]["owner"] + "." + field["payloadPath"]
        projection = field["projectionPath"]
        def arrays(path):
            parts = path.split('.')
            return ['.'.join(parts[:index + 1]) for index, part in enumerate(parts) if part.endswith('[]')]
        requests, responses = arrays(request), arrays(projection)
        if len(requests) != len(responses):
            raise ValueError(f'{page}/{field["code"]}: request/response array depths differ')
        for request_path, response_path in zip(requests, responses):
            identity = identities.get(response_path)
            if not isinstance(identity, dict) or identity.get('requestPath') != request_path:
                raise ValueError(f'{page}/{field["code"]}: missing or mismatched row identity {response_path}')
            keys = identity.get('keys')
            if not isinstance(keys, list) or not keys or any(
                not isinstance(key, dict) or set(key) != {'name', 'required'} or
                not isinstance(key['name'], str) or not key['name'] or not isinstance(key['required'], bool)
                for key in keys
            ) or len({key['name'] for key in keys}) != len(keys) or not any(key['required'] for key in keys):
                raise ValueError(f'{page}/{response_path}: invalid identity keys')
            used.add(response_path)
    if used != identities.keys():
        raise ValueError(f'{page}: unused row identity definitions {identities.keys() - used}')
    test_root = registry_root.parent / 'crates/services/web-server/tests/api_editor'
    for group in ('fieldChecks', 'collections', 'relations', 'auditChecks'):
        if not isinstance(contract.get(group), list):
            raise ValueError(f'{page}: missing {group} contracts')
        for check in contract[group]:
            verifier = check['verifier'].split('::')
            if len(verifier) != 3 or not check.get('description'):
                raise ValueError(f'{page}: invalid behavior check {check}')
            source = test_root / verifier[0] / (verifier[1] + '.rs')
            pattern = rf'pub\(crate\)\s+async\s+fn\s+{re.escape(verifier[2])}\s*\('
            if not source.is_file() or not re.search(pattern, source.read_text()):
                raise ValueError(f'{page}/{check["id"]}: verifier missing: {source}::{verifier[2]}')


def normalize_editor_filters(filters: list[str]) -> list[str]:
    if not isinstance(filters, list) or any(not isinstance(value, str) for value in filters):
        raise ValueError("editor filters must be a list of module prefixes")
    pages = "|".join(page.lower() for page in ACTIVE_PAGES)
    pattern = rf"case_editor_contract_web::(?:{pages})::(?:(?:fields|rows|relations|audit)::)?"
    if any(not re.fullmatch(pattern, value) for value in filters):
        raise ValueError("invalid editor test module prefix")
    return [value for value in sorted(set(filters))
            if not any(value != other and value.startswith(other) for other in filters)]


def expected_editor_tests(registry_root: Path) -> set[str]:
    expected = set()
    for page in ACTIVE_PAGES:
        contract = load_contract(registry_root, page)
        prefix = f"case_editor_contract_web::{page.lower()}"
        for field in contract["fields"]:
            if field.get("execution", {}).get("status") != "blocked":
                expected.add(f'{prefix}::fields::{test_name(field["code"])}')
        for group, category in (("fieldChecks", "fields"), ("collections", "rows"), ("relations", "relations"), ("auditChecks", "audit")):
            for check in contract[group]:
                expected.add(f'{prefix}::{category}::{check["id"]}')
    return expected


def generate(registry_root: Path, output_root: Path) -> dict[str, str]:
    outputs = {}
    output_root.mkdir(parents=True, exist_ok=True)
    for page_id in ACTIVE_PAGES:
        contract = load_contract(registry_root, page_id)
        validate_behavior_bindings(contract, registry_root)
        rendered = render_page(page_id, contract["fields"], contract)
        outputs[page_id] = rendered
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()

    outputs = generate(REPO_ROOT / "registry", DEFAULT_OUTPUT)
    stale = []
    for page_id, rendered in outputs.items():
        path = DEFAULT_OUTPUT / f"{page_id.lower()}.generated.rs"
        if args.write:
            path.write_text(rendered, encoding="utf-8")
        elif not path.exists() or path.read_text(encoding="utf-8") != rendered:
            stale.append(str(path.relative_to(REPO_ROOT)))
    if stale:
        print("generated editor contract tests are stale; run with --write")
        for path in stale:
            print(path)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
