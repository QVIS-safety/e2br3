#!/usr/bin/env python3
"""Generate Rust field tests and rule dispatch from validator-owned JSON."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import subprocess

from check_rule_tests import CRATE, ROOT, check_catalog, field_test_name

HEADER = "// @generated by validator/tools/generate_field_tests.py; do not edit.\n\n"


def formatted(source: str) -> str:
    return subprocess.run(
        ["rustfmt", "--edition", "2021", "--config-path", str(ROOT / "rustfmt.toml"), "--emit", "stdout"],
        input=HEADER + source, text=True, capture_output=True, check=True,
    ).stdout


def outputs() -> dict[Path, str]:
    check_catalog()
    rules = json.loads((CRATE / "rules.json").read_text())["rules"]
    files = {}
    for section in "cdefgh":
        module = f"case::sections::{section}::rule_tests"
        entries = [rule for rule in rules if rule["testModule"] == module]
        tests = (CRATE / f"src/case/sections/{section}/rule_tests.rs").read_text()
        for rule in entries:
            if not re.search(r"\b" + re.escape(rule["testName"]) + r"\b", tests):
                raise ValueError(f"missing Rust test declaration: {module}::{rule['testName']}")
        body = "pub(crate) const RULE_TESTS: &[(&str, fn())] = &[\n"
        body += "".join(f'({json.dumps(rule["ruleCode"])}, {rule["testName"]} as fn()),\n' for rule in entries)
        files[CRATE / f"src/case/sections/{section}/rule_test_bindings.rs"] = formatted(body + "];\n")
    modules = []
    for path in sorted((CRATE / "field-rules").glob("*.json")):
        page = json.loads(path.read_text())
        if not page["fields"]:
            continue
        module = page["pageId"].lower()
        modules.append(f"mod {module};\n")
        body = f'const MANIFEST: &str = include_str!("../../field-rules/{path.name}");\n\n'
        body += "".join(f'field_validation_test!({field_test_name(page["pageId"], field["fieldPath"])}, {json.dumps(field["fieldPath"])});\n'
                        for field in page["fields"])
        files[CRATE / f"src/field_tests/{module}.rs"] = formatted(body)
    # Module declarations refer to siblings of this included file.
    files[CRATE / "src/field_tests/generated.rs"] = HEADER + "".join(modules)
    return files


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, expected in outputs().items():
        if args.write:
            path.write_text(expected)
        elif not path.is_file() or path.read_text() != expected:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        raise SystemExit("stale validator field tests; run generate_field_tests.py --write: " + ", ".join(stale))


if __name__ == "__main__":
    main()
